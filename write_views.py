L("        return redirect('home')")
L('')
L("    if request.method == 'POST' and 'review_submit' in request.POST:")
L('        if not request.user.is_authenticated:')
L("            messages.error(request, 'You must be logged in to leave a review')")
L("            return redirect('login')")
L("        rating = request.POST.get('rating', '').strip()")
