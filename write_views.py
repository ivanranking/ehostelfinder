# get_university_options
L('def get_university_options():')
L('    university_names, seen = [], set()')
L('    def normalize(name):')
L('        if not name: return ""')
L('        n = name.strip().lower()')
L("        if 'makerere' in n and 'business school' in n: return 'Makerere University Business School'")
L("        if 'makerere' in n: return 'Makerere University'")
L("        return name.strip()")
L("    for name in KAMPALA_AREA_UNIVERSITIES + list(Hostel.objects.exclude(university='').values_list('university', flat=True)):")
L("        if name:")
L("            normalized = normalize(name)")
L("            if normalized.lower() not in seen:")
L("                university_names.append(normalized)")
L("                seen.add(normalized.lower())")
L("    return [{'name': n} for n in university_names]")
L('')

# home
L('def home(request):')
L("    university = request.GET.get('university', 'All Universities')")
L("    city = request.GET.get('city', '')")
L("    country = request.GET.get('country', '')")
L("    min_price = request.GET.get('min_price', '')")
L("    max_price = request.GET.get('max_price', '')")
L("    sort_by = request.GET.get('sort', '-created_at')")
L("    page = request.GET.get('page', 1)")
L("    valid_sorts = ['name', '-name', 'price', '-price', 'rating', '-rating', 'created_at', '-created_at']")
L("    if sort_by not in valid_sorts: sort_by = '-created_at'")
L("    hostels = Hostel.objects.all()")
L("    if university and university != 'All Universities': hostels = hostels.filter(university=university)")
L("    if city: hostels = hostels.filter(city__icontains=city)")
L("    if country: hostels = hostels.filter(country__icontains=country)")
L("    if min_price:")
L("        try: hostels = hostels.filter(price__gte=float(min_price)).distinct()")
L("        except ValueError: pass")
L("    if max_price:")
L("        try: hostels = hostels.filter(price__lte=float(max_price)).distinct()")
L("        except ValueError: pass")
L("    hostels = hostels.order_by(sort_by)")
L("    paginator = Paginator(hostels, 12)")
L("    try: page_obj = paginator.page(page)")
L("    except: page_obj = paginator.page(1)")
L("    cities_list = sorted(Hostel.objects.values_list('city', flat=True).exclude(city='').distinct())")
L("    countries_list = sorted(Hostel.objects.values_list('country', flat=True).exclude(country='').distinct())")
L("    universities = get_university_options()")
L("    rated_hostels = Hostel.objects.exclude(rating__isnull=True)")
L("    avg_rating = round(sum(float(h.rating) for h in rated_hostels) / rated_hostels.count(), 1) if rated_hostels.exists() else 0.0")
L("    hostel_list = []")
L("    for h in page_obj:")
L("        cover = h.images.filter(is_cover=True).first()")
L("        available_room = h.rooms.filter(status='Available').first()")
L("        hostel_list.append({")
L("            'id': str(h.id), 'name': h.name, 'description': h.description, 'city': h.city, 'country': h.country,")
L("            'university': h.university, 'image_url': h.image_url or (cover.image_url if cover else None),")
L("            'facilities': [{'name': f.facility_name, 'icon': f.icon or ''} for f in h.facilities.all()],")
L("            'available': h.available, 'rating': float(h.rating) if h.rating else round(float(h.average_rating), 1),")
L("            'distance': h.distance or 'Near campus',")
L("            'price': str(h.price) if h.price else (str(available_room.price_per_night) if available_room else '0'),")
L("            'amenities': h.amenities or [],")
L("        })")
L("    favorite_ids = []")
L("    if request.user.is_authenticated:")
L("        favorite_ids = list(Favorite.objects.filter(customer=request.user).values_list('hostel_id', flat=True))")
L("    return render(request, 'home.html', {")
L("        'hostels': hostel_list, 'cities': cities_list, 'countries': countries_list, 'universities': universities,")
L("        'selected_city': city, 'selected_country': country, 'selected_university': university, 'selected_sort': sort_by,")
L("        'total_hostels': Hostel.objects.count(), 'total_universities': len(universities), 'avg_rating': avg_rating,")
L("        'total_cities': len(cities_list), 'page_obj': page_obj, 'favorite_ids': [str(fid) for fid in favorite_ids],")
L("    })")
L('')

